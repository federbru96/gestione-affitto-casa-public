-- ---------- Tabelle ----------
create table public.tenants (
  id bigint generated by default as identity primary key,
  address text,
  tenant_name text,
  tenant_cf text,
  monthly_rent numeric,
  due_day integer
);

create table public.payments (
  id bigint generated by default as identity primary key,
  month text not null,
  rent_amount numeric not null,
  utility_amount numeric default 0,
  total numeric not null,
  status text default 'In attesa',
  pay_date date,
  utility_file_url text
);

create table public.bills (
  id bigint generated by default as identity primary key,
  payment_id bigint references public.payments(id) on delete cascade,
  utility_type text not null,
  total_bill_amount numeric not null,
  tenant_share numeric not null,
  file_url text not null
);

create table public.property_documents (
  id bigint generated by default as identity primary key,
  title text not null,
  file_url text not null,
  created_at timestamptz not null default now()
);

-- ---------- Proprietario (schema non esposto via API) ----------
create schema if not exists private;
revoke all on schema private from public;
grant usage on schema private to authenticated;

create table private.app_owners (
  user_id uuid primary key references auth.users(id) on delete cascade
);

create or replace function private.is_owner()
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1 from private.app_owners where user_id = (select auth.uid())
  );
$$;
revoke all on function private.is_owner() from public;
grant execute on function private.is_owner() to authenticated;

-- ---------- Row Level Security ----------
alter table public.tenants            enable row level security;
alter table public.payments           enable row level security;
alter table public.bills              enable row level security;
alter table public.property_documents enable row level security;

-- Lettura pubblica (vista inquilino)
create policy "lettura pubblica tenants"            on public.tenants            for select to anon, authenticated using (true);
create policy "lettura pubblica payments"           on public.payments           for select to anon, authenticated using (true);
create policy "lettura pubblica bills"              on public.bills              for select to anon, authenticated using (true);
create policy "lettura pubblica property_documents" on public.property_documents for select to anon, authenticated using (true);

-- Scrittura solo per il proprietario
create policy "proprietario gestisce tenants"            on public.tenants            for all to authenticated using (private.is_owner()) with check (private.is_owner());
create policy "proprietario gestisce payments"           on public.payments           for all to authenticated using (private.is_owner()) with check (private.is_owner());
create policy "proprietario gestisce bills"              on public.bills              for all to authenticated using (private.is_owner()) with check (private.is_owner());
create policy "proprietario gestisce property_documents" on public.property_documents for all to authenticated using (private.is_owner()) with check (private.is_owner());

revoke insert, update, delete, truncate
  on public.tenants, public.payments, public.bills, public.property_documents
  from anon;

-- ---------- Storage: bollette (PDF, max 5 MB) ----------
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('bollette', 'bollette', true, 5242880, array['application/pdf'])
on conflict (id) do update
  set public = true, file_size_limit = 5242880, allowed_mime_types = array['application/pdf'];

create policy "proprietario carica bollette"   on storage.objects for insert to authenticated with check (bucket_id = 'bollette' and private.is_owner());
create policy "proprietario modifica bollette" on storage.objects for update to authenticated using (bucket_id = 'bollette' and private.is_owner()) with check (bucket_id = 'bollette' and private.is_owner());
create policy "proprietario elimina bollette"  on storage.objects for delete to authenticated using (bucket_id = 'bollette' and private.is_owner());

